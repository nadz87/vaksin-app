export type MsgKey = keyof (typeof dict)['ms']

type I18n = { lang: Lang; setLang: (l: Lang) => void; t: (k: MsgKey | string) => string }
const I18nContext = createContext<I18n | null>(null)

function readStoredLang(): Lang {
  try {
    return localStorage.getItem('lang') === 'en' ? 'en' : 'ms'
  } catch {
    return 'ms'
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang)

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    document.documentElement.lang = l
    try {
      localStorage.setItem('lang', l)
    } catch {
      /* private mode: language just won't be remembered */
    }
  }, [])

  const t = useCallback(
    (k: string) => (dict[lang] as Record<string, string>)[k] ?? (dict.ms as Record<string, string>)[k] ?? k,
    [lang],
  )

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n outside I18nProvider')
  return ctx
}
