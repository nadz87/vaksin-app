// Local backend without Supabase. Usage:
//   node server/dev.mjs up     start db + rest + gateway, apply migrations and demo seed
//   node server/dev.mjs down   stop it (data is kept in the vaksin-dev_db-data volume)
// Secrets come from server/.env.dev (git-ignored), generated with random values the first time.
import { execFileSync } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { appendFileSync, existsSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { migrate } from './migrate.mjs'

const here = fileURLToPath(new URL('.', import.meta.url))
export const ENV_FILE = `${here}.env.dev`
const COMPOSE = ['compose', '-f', `${here}compose.dev.yml`, '--env-file', ENV_FILE]

// Every secret the local stack needs. Missing ones are added with random values, so an
// older .env.dev picks up new secrets without losing the ones the database already uses.
const SECRETS = ['DB_PASSWORD', 'AUTHENTICATOR_PASSWORD', 'AUTH_DB_PASSWORD', 'JWT_SECRET', 'OTP_PEPPER']

function readEnv() {
  if (!existsSync(ENV_FILE)) return {}
  return Object.fromEntries(
    readFileSync(ENV_FILE, 'utf8')
      .split(/\r?\n/)
      .filter((l) => /^[A-Z_]+=/.test(l))
      .map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]),
  )
}

export function devEnv() {
  const env = readEnv()
  const missing = SECRETS.filter((k) => !env[k])
  if (missing.length) {
    const text = existsSync(ENV_FILE) ? readFileSync(ENV_FILE, 'utf8') : '# Local development only. Generated by server/dev.mjs; never commit.\n'
    const lead = existsSync(ENV_FILE) ? (text.endsWith('\n') ? '' : '\n') : text
    appendFileSync(ENV_FILE, lead + missing.map((k) => `${k}=${randomBytes(32).toString('hex')}\n`).join(''))
    return readEnv()
  }
  return env
}

export function dbUrl(env, database = 'vaksin') {
  return `postgres://postgres:${env.DB_PASSWORD}@127.0.0.1:55432/${database}`
}

export function compose(...args) {
  execFileSync('docker', [...COMPOSE, ...args], { stdio: 'inherit' })
}

if (fileURLToPath(import.meta.url) === process.argv[1]) {
  const command = process.argv[2]
  const env = devEnv()
  if (command === 'up') {
    // Database first: PostgREST and the sign-in service can only sign in once the
    // migrations have created their roles and passwords.
    compose('up', '-d', '--build', '--wait', 'db')
    await migrate({
      url: dbUrl(env),
      authenticatorPassword: env.AUTHENTICATOR_PASSWORD,
      authDbPassword: env.AUTH_DB_PASSWORD,
      seed: true,
    })
    compose('up', '-d', '--build', '--wait')
    console.log('API ready at http://127.0.0.1:4011  (/rest/ = database API, /auth/ = sign-in)')
  } else if (command === 'down') {
    compose('down')
  } else {
    console.error('Usage: node server/dev.mjs up|down')
    process.exit(1)
  }
}
